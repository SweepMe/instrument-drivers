def describe_response_error(code: int) -> str:
    """Return a human-readable description for the leading ErrorID of a command response."""
    if code in RESPONSE_ERROR_CODES:
        return RESPONSE_ERROR_CODES[code]
    if -39999 <= code <= -30000:
        return "A required parameter has the wrong type."
    if -49999 <= code <= -40000:
        return "A required parameter is out of range."
    if -59999 <= code <= -50000:
        return "An optional parameter has the wrong type."
    if -69999 <= code <= -60000:
        return "An optional parameter is out of range."
    return "Unknown error code."


def describe_alarms(alarm_lists: list[list[int]]) -> str:
    """Format the nested alarm id lists returned by GetErrorID() into readable text.

    The first list contains the alarms of the controller and the motion algorithm, the following lists contain
    the alarms of the servo drives, one list per joint.
    """
    lines = []
    controller_alarms = alarm_lists[0] if alarm_lists else []
    for alarm_id in controller_alarms:
        if alarm_id:
            description = CONTROLLER_ALARMS.get(alarm_id, "Unknown alarm")
            lines.append(f"Controller alarm {alarm_id}: {description}")
    for joint, servo_alarms in enumerate(alarm_lists[1:], start=1):
        for alarm_id in servo_alarms:
            if alarm_id:
                description = SERVO_ALARMS.get(alarm_id, "Unknown alarm")
                lines.append(f"Servo alarm on joint {joint}, id {alarm_id}: {description}")
    return "\n".join(lines)
